export function detectLang(search = '', stored = null, navLang = 'es') {
  const q = new URLSearchParams(search).get('lang');
  if (LANGS.includes(q)) return q;
  if (LANGS.includes(stored)) return stored;
  return String(navLang || '').toLowerCase().startsWith('es') ? 'es' : (String(navLang).toLowerCase().startsWith('en') ? 'en' : 'es');
}

